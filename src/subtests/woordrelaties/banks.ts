/**
 * Woordrelaties: uit 5 woorden kies je de 2 die ongeveer hetzelfde (syn) of het tegenovergestelde (ant) betekenen.
 * Vorm: [woord 1, woord 2, soort, [3 andere woorden], uitleg]
 * De 3 andere woorden zijn zo gekozen dat ze met geen enkel ander woord in de set een synoniem- of tegenstellingspaar vormen.
 */
export type RelatieItem = [string, string, 'syn' | 'ant', [string, string, string], string];

const s = (a: string, b: string, f: [string, string, string], uitleg?: string): RelatieItem => [a, b, 'syn', f, uitleg ?? `${cap(a)} en ${b} betekenen ongeveer hetzelfde.`];
const t = (a: string, b: string, f: [string, string, string], uitleg?: string): RelatieItem => [a, b, 'ant', f, uitleg ?? `${cap(a)} is het tegenovergestelde van ${b}.`];
const cap = (w: string) => w.charAt(0).toUpperCase() + w.slice(1);

